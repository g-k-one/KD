// Builds KurwaDROP's own Forge atlas (public/vendor/forge/fx-kd.webp + kd-atlas.js) from our art:
// the KD coin, its edge, a golden-chicken feather, and white masks (glow, ring, spark, rays) that effects tint.
// Usage: node scripts/build-forge-atlas.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import sharp from 'sharp'

const CELL = 128
const COLS = 4

const coin = readFileSync('public/img/brand/coin.svg', 'utf8')
  .replace(/<svg[^>]*>/, '<svg width="112" height="112" viewBox="0 0 20 20" xmlns="http://www.w3.org/2000/svg">')

const cells = [
  ['coin', coin],
  // the coin seen edge-on while it spins
  [
    'coinE',
    `<svg width="112" height="112" viewBox="0 0 112 112" xmlns="http://www.w3.org/2000/svg">
      <defs><linearGradient id="e" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="#FEDF89"/><stop offset=".5" stop-color="#FDB022"/><stop offset="1" stop-color="#C46A12"/></linearGradient></defs>
      <rect x="2" y="47" width="108" height="18" rx="9" fill="url(#e)"/><rect x="10" y="53" width="92" height="3" rx="1.5" fill="#fff6cf" opacity=".7"/></svg>`,
  ],
  // golden chicken feather
  [
    'feather',
    `<svg width="112" height="112" viewBox="0 0 112 112" xmlns="http://www.w3.org/2000/svg">
      <defs><linearGradient id="f" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="#FFF3C4"/><stop offset=".45" stop-color="#F5C649"/><stop offset="1" stop-color="#C98A1E"/></linearGradient></defs>
      <path d="M86 10C58 14 30 38 22 74c-2 10-1 18 3 24 8-4 15-9 22-16 6 2 12 1 18-3-4-2-7-5-8-9 8 0 15-4 20-10-5-1-9-3-11-7 9-3 15-9 18-17-5 0-9-1-12-4 7-6 12-13 14-22z" fill="url(#f)"/>
      <path d="M84 14C62 36 42 62 25 98" stroke="#8a5513" stroke-width="3" stroke-linecap="round" fill="none"/></svg>`,
  ],
  // white masks: tinted per particle
  [
    'glow',
    `<svg width="128" height="128" xmlns="http://www.w3.org/2000/svg"><defs><radialGradient id="g"><stop offset="0" stop-color="#fff"/><stop offset=".35" stop-color="#fff" stop-opacity=".55"/><stop offset="1" stop-color="#fff" stop-opacity="0"/></radialGradient></defs><circle cx="64" cy="64" r="64" fill="url(#g)"/></svg>`,
  ],
  [
    'ring',
    `<svg width="128" height="128" xmlns="http://www.w3.org/2000/svg"><defs><radialGradient id="r"><stop offset=".72" stop-color="#fff" stop-opacity="0"/><stop offset=".86" stop-color="#fff"/><stop offset="1" stop-color="#fff" stop-opacity="0"/></radialGradient></defs><circle cx="64" cy="64" r="64" fill="url(#r)"/></svg>`,
  ],
  [
    'spark',
    `<svg width="128" height="128" xmlns="http://www.w3.org/2000/svg"><defs><radialGradient id="s"><stop offset="0" stop-color="#fff"/><stop offset="1" stop-color="#fff" stop-opacity="0"/></radialGradient></defs>
      <path d="M64 4C67 50 78 61 124 64 78 67 67 78 64 124 61 78 50 67 4 64 50 61 61 50 64 4Z" fill="#fff"/><circle cx="64" cy="64" r="22" fill="url(#s)"/></svg>`,
  ],
  [
    'rays',
    `<svg width="128" height="128" xmlns="http://www.w3.org/2000/svg"><defs><radialGradient id="m"><stop offset="0" stop-color="#fff"/><stop offset="1" stop-color="#fff" stop-opacity="0"/></radialGradient><mask id="k"><circle cx="64" cy="64" r="64" fill="url(#m)"/></mask></defs>
      <g mask="url(#k)" fill="#fff">${Array.from({ length: 12 }, (_, i) => `<path d="M64 64 L60 0 L68 0Z" transform="rotate(${i * 30} 64 64)"/>`).join('')}</g></svg>`,
  ],
  // ember: a small hot dot with a white core (tinted warm)
  [
    'ember',
    `<svg width="128" height="128" xmlns="http://www.w3.org/2000/svg"><defs><radialGradient id="h"><stop offset="0" stop-color="#fff"/><stop offset=".25" stop-color="#fff" stop-opacity=".9"/><stop offset=".6" stop-color="#fff" stop-opacity=".25"/><stop offset="1" stop-color="#fff" stop-opacity="0"/></radialGradient></defs><circle cx="64" cy="64" r="40" fill="url(#h)"/></svg>`,
  ],
]

// clubs of smoke from scripts/build-smoke-sprites.py (white, tinted per particle)
for (const n of [1, 2, 3, 4]) cells.push([`smoke${n}`, readFileSync(`scripts/forge-art/smoke${n}.png`)])

const rows = Math.ceil(cells.length / COLS)
const composites = await Promise.all(
  cells.map(async ([, svg], i) => {
    const png = await sharp(Buffer.isBuffer(svg) ? svg : Buffer.from(svg)).resize(CELL, CELL, { fit: 'contain', background: { r: 0, g: 0, b: 0, alpha: 0 } }).png().toBuffer()
    return { input: png, left: (i % COLS) * CELL, top: Math.floor(i / COLS) * CELL }
  }),
)
await sharp({ create: { width: COLS * CELL, height: rows * CELL, channels: 4, background: { r: 0, g: 0, b: 0, alpha: 0 } } })
  .composite(composites)
  .webp({ quality: 92, alphaQuality: 100 })
  .toFile('public/vendor/forge/fx-kd.webp')

const atlas = { cols: COLS, rows, cell: CELL, trim: cells.map(() => [0, 0, 1, 1]), map: Object.fromEntries(cells.map(([n], i) => [n, i])) }
// Classic script loaded after 16e-forge-atlas.js: adds the 'kd' entry to the engine's global atlas map
writeFileSync('public/vendor/forge/kd-atlas.js', `// generated by scripts/build-forge-atlas.mjs — do not edit
FX_ATLAS.kd = ${JSON.stringify(atlas)};
`)
console.log('fx-kd.webp', cells.length, 'cells')
